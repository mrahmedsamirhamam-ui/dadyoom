JOIN public.units u ON u.id=l.unit_id JOIN public.grades g ON g.id=u.grade_id
JOIN public.curricula c ON c.id=g.curriculum_id JOIN public.countries co ON co.id=c.country_id
WHERE co.code=p.country AND g.grade_number=p.grade AND l.title=p.title AND l.lesson_type='reading'
AND l.status='published' AND l.source_pdf_url IS NULL
AND l.content=p.old_body AND length(btrim(l.content))<600
)
UPDATE public.lessons l SET content=e.new_body,learning_objectives=e.objectives,updated_at=now()
FROM eligible e WHERE l.id=e.id
RETURNING l.id,l.title,length(l.content) chars;