DO $guard$
DECLARE found_count integer; bad_count integer;
BEGIN
 SELECT count(*) INTO found_count FROM bh_g1_unit1_four_subjects;
 IF found_count<>4 THEN RAISE EXCEPTION 'Expected 4 authored source components'; END IF;
 SELECT count(*) INTO bad_count
 FROM bh_g1_unit1_four_subjects s
 LEFT JOIN public.lessons l ON l.id=s.lesson_id
 LEFT JOIN public.units u ON u.id=l.unit_id
 LEFT JOIN public.grades g ON g.id=u.grade_id
 LEFT JOIN public.curricula cu ON cu.id=g.curriculum_id
 LEFT JOIN public.countries c ON c.id=cu.country_id
 WHERE l.id IS NULL OR l.title<>s.exact_title OR c.code<>'BH'
   OR g.grade_number<>1 OR l.semester<>1 OR l.status<>'published'
   OR u.title<>'الوحدة الأولى: عائلتنا'
   OR length(l.content)<>s.old_length
   OR l.content LIKE '%[ضاديوم — إضافة شرح أصلي مستقلة مرتبطة بعناصر خطة 2026–2027]%'
   OR length(s.original_subject_enrichment)<1100
   OR position(s.official_listening_heading in s.original_subject_enrichment)=0
   OR EXISTS(SELECT 1 FROM public.student_lesson_progress p WHERE p.lesson_id=l.id)
   OR EXISTS(SELECT 1 FROM public.question_attempts qa JOIN public.questions q ON q.id=qa.question_id WHERE q.lesson_id=l.id)
   OR EXISTS(SELECT 1 FROM public.lesson_activity_attempts aa JOIN public.lesson_activities a ON a.id=aa.activity_id WHERE a.lesson_id=l.id);
 IF bad_count<>0 THEN RAISE EXCEPTION 'Rollback; unsafe lesson scope, source text, already applied, or learner history: %',bad_count; END IF;
END $guard$;

