export type StudioFocus =
  | "sustainability"
  | "localCitizenship"
  | "globalCitizenship"
  | "islamicStudies";

export type ArabicSkill = "grammar" | "reading" | "writing" | "speaking";

export type StudioInput = {
  lessonTitle: string;
  learningOutcome: string;
  grade: number;
  country: string;
  skill: ArabicSkill;
  focus: Record<StudioFocus, boolean>;
};

export const FOCUS_LABELS: Record<StudioFocus, string> = {
  sustainability: "الاستدامة والتعليم الأخضر",
  localCitizenship: "المواطنة المحلية",
  globalCitizenship: "المواطنة العالمية",
  islamicStudies: "التكامل مع التربية الإسلامية",
};

export const DEFAULT_FOCUS: Record<StudioFocus, boolean> = {
  sustainability: true,
  localCitizenship: true,
  globalCitizenship: true,
  islamicStudies: false,
};

