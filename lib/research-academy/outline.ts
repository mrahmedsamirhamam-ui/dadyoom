/**
 * Research Academy: deterministic learning scaffolds.
 * Never invents studies, citations, outcomes, or evidence.
 */
export type ResearchMethod = "qualitative" | "quantitative" | "mixed" | "undecided";
export type SourceType = "article" | "book" | "web";

export type ResearchInput = {
  topic: string;
  problem: string;
  objective: string;
  questions: string;
  method: ResearchMethod;
  population: string;
};

export type OutlineSection = {
  title: string;
  guidance: string;
  draft: string;
};

export type ResearchOutline = {
  title: string;
  sections: OutlineSection[];
  checks: string[];
};

export type ReferenceInput = {
  author: string;
  year: string;
  title: string;
  publisher: string;
  url: string;
  type: SourceType;
};

const clean = (value: string): string => value.trim().replace(/\s+/gu, " ");
const present = (value: string, fallback: string): string => clean(value) || fallback;

export const methodLabels: Record<ResearchMethod, string> = {
  qualitative: "وصفي نوعي",
  quantitative: "كمي",
  mixed: "مختلط",
  undecided: "لم أحدد المنهج بعد",
};

export function buildResearchOutline(input: ResearchInput): ResearchOutline {
  const topic = clean(input.topic);
  const questionLines = input.questions.split(/\r?\n/u).map(clean).filter(Boolean);
  const researchQuestions = questionLines.map((q, index) => `${index + 1}. ${q}`).join("\n");
  const method = input.method === "undecided" ? "" : methodLabels[input.method];

  return {
    title: present(topic, "[اكتب عنوان بحثك هنا]"),
    sections: [
      {
        title: "1. مقدمة البحث وسياقه",
        guidance: "قدّم خلفية موثقة عن المجال، وبيّن ما هو معروف وما يحتاج إلى دراسة، دون اختلاق نتائج.",
        draft: topic ? `يتناول هذا البحث موضوع «${topic}». [أضف خلفية مدعومة بمراجع قرأتها فعلًا].` : "[اكتب موضوع البحث وخلفيته مع مصادر موثوقة].",
      },
      {
        title: "2. مشكلة البحث",
        guidance: "حدّد الظاهرة والفجوة البحثية وحدود المشكلة، وميّز بين رأيك والدليل المنشور.",
        draft: present(input.problem, "[صِغ المشكلة البحثية في عبارة محددة قابلة للدراسة]."),
      },
      {
        title: "3. الهدف من البحث",
        guidance: "صِغ هدفًا رئيسيًا قابلًا للتحقق، ثم أهدافًا فرعية عند الحاجة.",
        draft: present(input.objective, "[اكتب هدفًا محددًا قابلًا للقياس أو التحقق]."),
      },
      {
        title: "4. أسئلة البحث",
        guidance: "اربط كل سؤال بالمشكلة والهدف؛ لا تفترض إجابات مسبقة.",
        draft: researchQuestions || "[اكتب سؤالًا بحثيًا واضحًا في كل سطر].",
      },
      {
        title: "5. المنهج والإجراءات",
        guidance: "اذكر سبب اختيار المنهج، والعينة، والأداة، وطريقة التحليل، والاعتبارات الأخلاقية.",
        draft: [
          `المنهج المقترح: ${method || "[اختر المنهج بعد فحص أسئلة البحث]"}.`,
          `مجتمع الدراسة أو مادتها: ${present(input.population, "[حدّد المجتمع أو النصوص أو الوثائق محل الدراسة]")}.`,
          "أدوات جمع البيانات وتحليلها: [حدّد الأدوات وسبب ملاءمتها].",
          "الضوابط الأخلاقية والموافقات اللازمة: [تحقق منها قبل جمع البيانات].",
        ].join("\n"),
      },
      {
        title: "6. الدراسات السابقة",
        guidance: "لخّص الدراسات التي اطلعت عليها، مع توثيق نتائجها وحدودها والمقارنة بينها.",
        draft: "[أدرج فقط الدراسات التي تحققت من بيانات نشرها واطلعت على مضمونها].",
      },
      {
        title: "7. النتائج والمناقشة",
        guidance: "لا تكتب نتيجة إلا بعد جمع البيانات وتحليلها؛ هذه مساحة تعليمية وليست نتائج مولّدة.",
        draft: "[يُستكمل هذا القسم بعد إجراء البحث وتحليل البيانات الفعلية].",
      },
      {
        title: "8. المراجع والملاحق",
        guidance: "وثّق المصادر التي استخدمتها فعلًا وفق دليل جامعتك ونمط التوثيق المعتمد.",
        draft: "[أضف مراجع حقيقية متحققًا منها، مع نسخ أدوات البحث وموافقاته عند الحاجة].",
      },
    ],
    checks: [
      "هل يوجد توافق واضح بين المشكلة والهدف وأسئلة البحث؟",
      "هل كل معلومة مقتبسة موثقة بمصدر تحققت منه؟",
      "هل توضح الإجراءات خصوصية المشاركين وموافقتهم عند اللزوم؟",
      "هل كل نتيجة مبنية على بيانات فعلية وليست افتراضًا؟",
      "هل راجعت دليل جامعتك ومتطلبات لجنة الأخلاقيات؟",
    ],
  };
}

/**
 * An intentionally preliminary bibliographic entry, NOT a full APA7 validator.
 * No source is generated by the system, and the user supplies every field.
 */
export function formatReferenceDraft(source: ReferenceInput):
  { text: string; errors: string[] } {
  const author = clean(source.author);
  const year = clean(source.year);
  const title = clean(source.title);
  const publisher = clean(source.publisher);
  const url = clean(source.url);
  const errors: string[] = [];

  if (!author) errors.push("أدخل المؤلف أو المؤسسة المسؤولة.");
  if (!title) errors.push("أدخل عنوان المصدر.");
  if (!/^\d{4}$/u.test(year) || Number(year) < 1500 || Number(year) > new Date().getFullYear()) {
    errors.push("أدخل سنة نشر صحيحة من أربعة أرقام، أو تحقق من بيانات المصدر.");
  }
  if (source.type === "article" && !publisher) {
    errors.push("أدخل اسم المجلة أو الجهة الناشرة للمقال.");
  }
  if (url) {
    try {
      const parsed = new URL(url);
      if (!["http:", "https:"].includes(parsed.protocol)) errors.push("الرابط يجب أن يبدأ بـ https:// أو http://.");
    } catch {
      errors.push("أدخل رابطًا صحيحًا للمصدر.");
    }
  }
  if (errors.length) return { text: "", errors };

  return {
    text: [`${author}. (${year}). ${title}.`, publisher ? `${publisher}.` : "", url].filter(Boolean).join(" "),
    errors: [],
  };
}
